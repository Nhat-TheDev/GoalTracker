import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const skillPath = path.join(root, '.claude', 'skills', 'goaltracker', 'SKILL.md');
const outPath = path.join(root, 'src', 'skillContent.ts');

const content = readFileSync(skillPath, 'utf-8');
const escaped = content.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-skill-content.mjs from .claude/skills/goaltracker/SKILL.md — do not edit directly.\nexport const SKILL_MD = \`${escaped}\`;\n`
);
console.log('Generated src/skillContent.ts from .claude/skills/goaltracker/SKILL.md');
